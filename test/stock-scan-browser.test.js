import assert from "node:assert/strict";
import test from "node:test";
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import { startStockTestServer, stockTestLogin } from "./helpers/stock-scan-server.js";

const executablePath = process.env.TEST_STOCK_SCAN_CHROME;
const output = process.env.TEST_STOCK_SCAN_ARTIFACTS;
const scan = "/api/stock/scan";
const mode = "CMD:OUT";

test("Chromium Stock Scan: HID, pointer review, timeout retry, cross-tab stock, and print", { skip: !executablePath, timeout: 90_000 }, async t => {
  const { chromium } = await import(process.env.TEST_STOCK_SCAN_PLAYWRIGHT || "playwright");
  const base = await startStockTestServer(t);
  if (output) await mkdir(output, { recursive: true });
  const browser = await chromium.launch({ executablePath, args: ["--no-sandbox", "--disable-dev-shm-usage", "--disable-gpu"] });
  t.after(() => browser.close());
  const owner = await stockTestLogin(base);
  const employee = await owner.ok("/api/employees", "POST", {
    name: "Mariano Fadi", startDate: "2026-01-01", employmentStatus: "ACTIVE"
  });
  const staffBarcode = (await owner.ok(scan + "/staff")).staff.find(row => row.code === employee.code).barcode;
  const createRoll = (name, sku, width, stock) => owner.ok("/api/materials", "POST", { name, sku, stock, rollWidthCm: width, stockMethod: "ROLL", category: "Roll Outdoor", unit: "m²" });
  const first = await createRoll("FL 280 Glossy 110", "BHN-FL280/110-TEST", 110, 10);
  const second = await createRoll("FL 280 Glossy 220", "BHN-FL280/220-TEST", 220, 5);
  const count = async material => (await owner.ok(`${scan}/catalog/${material.id}`)).material.balance;
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  const page = await desktop.newPage();
  const errors = [];
  const fetched = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => fetched.push(new URL(request.url()).pathname));
  const shot = async (view, file) => { if (output) await view.screenshot({ path: join(output, file), fullPage: true }); };

  await page.goto(base + "/stock/scan");
  await page.locator('[name="username"]').fill("admin");
  await page.locator('[name="pin"]').fill("4321");
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await page.locator("#scan-ready").getByText("Siap scan").waitFor();
  const stock = await desktop.newPage();
  await stock.goto(base + "/#stock");
  await stock.getByRole("link", { name: "Stock Scan", exact: true }).waitFor();
  await stock.getByText("Belum ada mutasi pada tanggal ini.").waitFor();
  await page.bringToFront();
  const read = async (value, view = page) => {
    const input = view.locator("#barcode-input");
    await input.pressSequentially(value);
    await input.press("Enter");
  };
  const style = (target, property) => target.evaluate((element, key) => getComputedStyle(element)[key], property);
  const scanStaff = async (view = page) => {
    await read(staffBarcode, view);
    await view.locator("#scan-staff.assigned").getByText(employee.name, { exact: true }).waitFor();
  };
  const dialog = page.getByRole("dialog");
  const finish = page.getByRole("button", { name: "Selesai Scan", exact: true });
  assert.equal(await page.getByText("Bahan terakhir", { exact: true }).count(), 0);
  assert.equal(await page.getByText("Riwayat Saya", { exact: true }).count(), 0);
  assert.deepEqual(await page.locator(".scan-staff-label img").evaluate(async icon => {
    await icon.decode();
    return [icon.naturalWidth, icon.naturalHeight, icon.clientWidth, icon.clientHeight];
  }), [20, 20, 20, 20]);
  assert.equal(await style(page.locator(".scan-work"), "width"), "540px");
  const reader = page.locator("#barcode-input");
  const scannerIcon = page.locator(".scanner-icon");
  const activeScannerIcon = page.locator(".scanner-icon-active");
  assert.equal(await style(reader, "height"), "52px");
  assert.equal(await activeScannerIcon.isVisible(), true);
  await page.locator("#scan-note").focus();
  assert.equal(await style(reader, "height"), "50px");
  assert.equal(await scannerIcon.isVisible(), true);
  assert.equal(await activeScannerIcon.isVisible(), false);
  for (const icon of [scannerIcon, activeScannerIcon]) {
    assert.deepEqual(await icon.evaluate(async img => {
      await img.decode();
      return [img.naturalWidth, img.naturalHeight];
    }), [24, 24]);
  }
  await reader.focus();
  await read(`MAT:${first.id}`);
  await page.locator("#scan-message").getByText(/terlebih dahulu/).waitFor();
  await read(mode);
  const outgoing = page.getByRole("button", { name: "Stok Keluar", exact: true });
  assert.equal(await outgoing.getAttribute("aria-pressed"), "true");
  assert.equal(await style(outgoing, "backgroundColor"), "rgb(210, 45, 36)");
  await read("QTY:3");
  await page.locator("#scan-message").getByText(/sebelum memilih jumlah/).waitFor();
  await read(`MAT:${first.id}`);
  await read("QTY:5");
  await read(`MAT:${first.id}`);
  assert.equal(await page.getByLabel("Jumlah roll FL 280 Glossy 110", { exact: true }).inputValue(), "5");
  await read("CMD:IN");
  await page.locator("#scan-message").getByText(/masih berisi bahan/).waitFor();
  await read("CMD:REVIEW");
  await page.locator("#scan-message").getByText(/scan barcode staff/).waitFor();
  assert.equal(await finish.isDisabled(), true);
  assert.equal(await style(finish, "opacity"), "0.4");
  assert.equal(await dialog.count(), 0);
  await read("STF:Eemp-tidak-ada");
  await page.locator("#scan-message").getByText(/Barcode staff tidak dikenal/).waitFor();
  await scanStaff();
  await read("CMD:REVIEW");
  await dialog.getByText("Konfirmasi Stok Keluar").waitFor();
  await dialog.getByText(/Staff Mariano Fadi/).waitFor();
  assert.equal(await style(dialog.getByText("−5 roll", { exact: true }), "color"), "rgb(255, 41, 27)");
  assert.equal(await page.evaluate(() => document.activeElement.id), "review-title");
  await page.keyboard.type("CMD:IN");
  await page.keyboard.press("Enter");
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).evaluate(button => button.click());
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).press("Space");
  assert.equal(await count(first), 10);
  await dialog.getByRole("button", { name: "Batalkan" }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByText("Untuk mengisi, scan barcode staff", { exact: true }).waitFor();
  assert.equal(await count(first), 10);

  await read(mode);
  await read(`MAT:${first.id}`);
  assert.equal(await page.getByRole("button", { name: "Kurangi jumlah roll FL 280 Glossy 110" }).isDisabled(), true);
  await read(`MAT:${second.id}`);
  await page.getByRole("button", { name: "Tambah jumlah roll FL 280 Glossy 220" }).click();
  assert.equal(await page.getByLabel("Jumlah roll FL 280 Glossy 220", { exact: true }).inputValue(), "2");
  assert.equal(await page.getByLabel("Jumlah roll FL 280 Glossy 110", { exact: true }).inputValue(), "1");
  assert.equal(await page.locator("#scan-roll-count").textContent(), "3 roll");
  assert.equal(await page.evaluate(() => document.activeElement.id), "barcode-input");
  await read("QTY:2");
  await page.locator("#scan-note").fill("Buka roll untuk produksi pagi");
  await page.locator("#barcode-input").focus();
  await shot(page, "00-stock-scan-staff-kosong.png");
  await scanStaff();
  await shot(page, "01-stock-scan-desktop.png");
  await page.getByRole("button", { name: "Selesai Scan", exact: true }).click();
  await dialog.getByText("Saldo 5 → 3 roll").waitFor();
  await shot(page, "02-review-desktop.png");

  const sent = [];
  await page.route("**/api/stock/scan/commit", async route => {
    sent.push(route.request().postDataJSON());
    const response = await route.fetch();
    if (sent.length === 1) await route.abort("failed");
    else await route.fulfill({ response });
  });
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).dblclick();
  await dialog.getByText(/Hasil penyimpanan belum diketahui/).waitFor();
  assert.equal(sent.length, 1);
  assert.equal(await count(first), 9);
  assert.equal(await count(second), 3);
  await page.reload();
  await dialog.getByText(/sebelumnya belum diketahui/).waitFor();
  await dialog.getByText(/Staff Mariano Fadi/).waitFor();
  await dialog.getByRole("button", { name: "Cek & ulangi" }).click();
  await page.locator("#scan-message").getByText(/Stok Keluar tersimpan/).waitFor();
  assert.deepEqual(sent[1], sent[0]);
  assert.equal(sent[0].staffBarcode, staffBarcode);
  await page.getByText("Untuk mengisi, scan barcode staff", { exact: true }).waitFor();
  assert.equal(await count(first), 9);
  assert.equal(await count(second), 3);
  assert.ok(!fetched.includes("/api/bootstrap"));
  assert.ok(!fetched.includes("/vendor/jsbarcode-code128.min.js"));

  await read("CMD:IN");
  await scanStaff();
  await read(`MAT:${first.id}`);
  await read("CMD:REVIEW");
  await owner.ok("/api/inventory/" + first.sku.replace("/", "%2F"), "PATCH", { change: 1, reason: "Penerimaan manual uji" });
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).click();
  await dialog.getByText(/Saldo atau informasi bahan berubah/).waitFor();
  await dialog.getByText("Saldo 10 → 11 roll").waitFor();
  assert.equal(await count(first), 10);
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).click();
  await page.locator("#scan-message").getByText(/Stok Masuk tersimpan/).waitFor();
  assert.equal(await count(first), 11);

  await scanStaff();
  await read("CMD:IN");
  await read(`MAT:${first.id}`);
  await read("CMD:REVIEW");
  await dialog.getByText("Konfirmasi Stok Masuk").waitFor();
  const inactive = await owner.ok("/api/employees/" + employee.id, "PUT", { ...employee, active: false });
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  await page.getByText("Untuk mengisi, scan barcode staff", { exact: true }).waitFor();
  await page.locator("#scan-message").getByText(/karyawan sudah tidak aktif/).waitFor();
  assert.equal(await page.locator("#scan-roll-count").textContent(), "1 roll");
  assert.equal(await page.getByRole("button", { name: "Selesai Scan" }).isDisabled(), true);
  assert.equal(await count(first), 11);
  await owner.ok("/api/employees/" + employee.id, "PUT", { ...inactive, active: true });

  const secondMutation = stock.locator(".stock-movement").filter({ hasText: second.name });
  await secondMutation.getByText("Barcode · Staff Mariano Fadi · Dicatat oleh Owner Manna").waitFor();
  assert.match(await stock.locator("tr").filter({ hasText: second.sku }).innerText(), /3 roll/);
  await secondMutation.getByRole("button", { name: "Koreksi" }).click();
  const correction = stock.getByRole("dialog");
  await correction.getByText("Koreksi Stok Barcode").waitFor();
  await correction.locator('[name="reason"]').fill("Koreksi hitung fisik uji");
  await correction.locator('[name="physicalConfirmed"]').check();
  await correction.getByRole("button", { name: "Simpan Koreksi" }).click();
  await correction.waitFor({ state: "hidden" });
  await secondMutation.getByText("Koreksi Stok · Owner Manna").waitFor();
  assert.equal(await count(second), 5);
  await stock.locator("#stock-search").fill("FL 280 Glossy");
  if (output) await stock.screenshot({ path: join(output, "05-mutasi-stok.png") });

  const tablet = await browser.newContext({ viewport: { width: 768, height: 1024 }, deviceScaleFactor: 1, hasTouch: true, storageState: await desktop.storageState() });
  const touch = await tablet.newPage();
  await touch.goto(base + "/stock/scan");
  await touch.locator("#scan-ready").getByText("Siap scan").waitFor();
  await read("CMD:IN", touch);
  const incoming = touch.getByRole("button", { name: "Stok Masuk", exact: true });
  assert.equal(await incoming.getAttribute("aria-pressed"), "true");
  assert.equal(await style(incoming, "backgroundColor"), "rgb(14, 130, 88)");
  await scanStaff(touch);
  await read(`MAT:${first.id}`, touch);
  const quantity = touch.getByLabel("Jumlah roll FL 280 Glossy 110", { exact: true });
  await quantity.fill("4");
  await touch.getByRole("button", { name: "Tambah jumlah roll FL 280 Glossy 110" }).tap();
  assert.equal(await quantity.inputValue(), "5");
  await touch.getByRole("button", { name: "Kurangi jumlah roll FL 280 Glossy 110" }).tap();
  assert.equal(await quantity.inputValue(), "4");
  await shot(touch, "03-stock-scan-tablet.png");
  assert.equal(await touch.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await touch.setViewportSize({ width: 360, height: 800 });
  assert.equal(await touch.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await shot(touch, "08-stock-scan-small.png");
  await touch.setViewportSize({ width: 768, height: 1024 });
  await touch.getByRole("button", { name: "Selesai Scan", exact: true }).tap();
  const tabletDialog = touch.getByRole("dialog");
  await tabletDialog.getByText("Saldo 11 → 15 roll").waitFor();
  assert.equal(await style(tabletDialog.getByText("+4 roll", { exact: true }), "color"), "rgb(20, 150, 106)");
  await shot(touch, "04-review-tablet.png");
  await tabletDialog.getByRole("button", { name: "Konfirmasi", exact: true }).tap();
  await touch.locator("#scan-message").getByText(/Stok Masuk tersimpan/).waitFor();
  assert.equal(await count(first), 15);

  const labels = await desktop.newPage();
  await labels.goto(base + "/stock/scan/print");
  await labels.locator("#barcode-category").selectOption("Roll Outdoor");
  await labels.getByRole("button", { name: "Pilih kategori ini" }).click();
  await labels.getByText("11 label · A4").waitFor();
  assert.equal(await labels.locator("svg").count(), 11);
  await labels.getByLabel(/Mariano Fadi/).check();
  await labels.getByText("12 label · A4").waitFor();
  const staffLabel = labels.locator(".barcode-label").filter({ hasText: employee.name });
  assert.equal(await staffLabel.locator("svg").count(), 1);
  assert.equal(await staffLabel.locator("code").textContent(), staffBarcode);
  await shot(labels, "06-cetak-barcode.png");
  if (output) await labels.pdf({ path: join(output, "test-a4.pdf"), preferCSSPageSize: true, printBackground: true });
  await labels.locator("#paper-size").selectOption("a3plus");
  await labels.getByText("12 label · A3+").waitFor();
  assert.equal(await labels.locator("svg").count(), 12);
  await shot(labels, "07-cetak-barcode-a3plus.png");
  if (output) await labels.pdf({ path: join(output, "test-a3plus.pdf"), preferCSSPageSize: true, printBackground: true });

  await labels.getByRole("button", { name: "Kosongkan" }).click();
  await labels.locator("#print-commands").uncheck();
  await labels.locator("#print-quantities").uncheck();
  await labels.getByLabel(/Mariano Fadi/).uncheck();
  await labels.locator("#paper-size").selectOption("a4");
  await labels.getByLabel(/Owner Manna/).check();
  await labels.getByText("1 label · A4").waitFor();
  const ownerLabel = labels.locator(".barcode-label").filter({ hasText: owner.user.name });
  assert.equal(await ownerLabel.locator("p").textContent(), "Owner");
  assert.equal(await ownerLabel.locator("svg").count(), 1);
  const printedOwnerBarcode = await ownerLabel.locator("code").textContent();
  assert.match(printedOwnerBarcode, /^OWN:U[a-zA-Z0-9_-]{22}$/);
  await shot(labels, "09-cetak-barcode-owner.png");
  if (output) await labels.pdf({ path: join(output, "test-owner-a4.pdf"), preferCSSPageSize: true });

  await page.reload();
  await page.locator("#scan-ready").getByText("Siap scan").waitFor();
  await read("CMD:OUT");
  await read(`MAT:${first.id}`);
  assert.equal(await finish.isDisabled(), true);
  await read(printedOwnerBarcode);
  const ownerChip = page.locator("#scan-staff.assigned").getByText(owner.user.name, { exact: true });
  await ownerChip.waitFor();
  assert.equal(await style(ownerChip, "height"), "28px");
  assert.equal(await style(ownerChip, "backgroundColor"), "rgb(82, 98, 122)");
  assert.equal(await finish.isEnabled(), true);
  await shot(page, "10-scan-staff-owner.png");
  await finish.click();
  await dialog.getByText(/Staff Owner Manna/).waitFor();
  await dialog.getByRole("button", { name: "Konfirmasi", exact: true }).click();
  await page.locator("#scan-message").getByText(/Stok Keluar tersimpan/).waitFor();
  await stock.getByText("Barcode · Staff Owner Manna", { exact: true }).waitFor();
  assert.equal(await count(first), 14);
  assert.deepEqual(errors, []);
});
